"""Compile-only fixes for Vineflower's erased-type / mixin-interface casts.

Mixin injects interfaces into vanilla classes at runtime. javac cannot see that, so
`itemStack instanceof ModType` is rejected as "incompatible types" even though the
bytecode is exactly that. Casting the left operand to Object restores the same
checkcast semantics without changing generated bytecode.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
BASE = 'src/main/java/com/larpclient/'

# (file, old, new, expected number of occurrences)
FIXES = [
    ('Sha256Digest.java',
     'var0 instanceof Sha256Digest.Type_c',
     '(Object)var0 instanceof Sha256Digest.Type_c', 4),
    ('w0.java',
     'var0 instanceof w0.Type_l',
     '(Object)var0 instanceof w0.Type_l', 2),
    ('LinuxMediaSessions.java',
     'if (var12 instanceof Map) {',
     'if ((Object)var12 instanceof Map) {', 1),
    ('LinuxMediaSessions.java',
     'Map var9 = (Map)var12;',
     'Map var9 = (Map)(Object)var12;', 1),
    ('PlayerJointTransforms.java',
     '((ModelPartAccessor)this.b[var2])',
     '((ModelPartAccessor)(Object)this.b[var2])', 1),
    ('PlayerJointTransforms.java',
     '((ModelPartAccessor)var0)',
     '((ModelPartAccessor)(Object)var0)', 1),
    ('FakeSpawnerController.java',
     'return (Collection<MobSpawnerBlockEntity>)(var4 == null ? List.of() : var4);',
     'return (Collection<MobSpawnerBlockEntity>)(Object)(var4 == null ? List.of() : var4);', 1),
    ('ProxySessionJoin.java',
     'var12 = uAsObject(var0, var5);',
     'var12 = (ProxySessionJoin.Type_x)uAsObject(var0, var5);', 1),
    ('SahurArticulation.java',
     'var5[((Set)var26.get(var30)).iterator().next()]',
     'var5[((Integer)((Set)var26.get(var30)).iterator().next()).intValue()]', 1),
    ('SahurArticulation.java',
     'var3[var7.get(var72) * 5 + var75]',
     'var3[((Integer)var7.get(var72)) * 5 + var75]', 1),
]

# apply per-file so multiple edits to one file accumulate
by_file = {}
for f, old, new, n in FIXES:
    by_file.setdefault(f, []).append((old, new, n))

for f, edits in by_file.items():
    p = BASE + f
    s = open(p, encoding='utf-8', errors='replace').read()
    for old, new, n in edits:
        got = s.count(old)
        if got != n:
            print('  SKIP %s: expected %d occurrences of %r, found %d' % (f, n, old[:60], got))
            continue
        s = s.replace(old, new)
        print('  OK   %s: %d x %s' % (f, n, old[:60]))
    open(p, 'w', encoding='utf-8', newline='').write(s)
print('done')
